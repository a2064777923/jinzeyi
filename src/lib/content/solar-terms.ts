const solarTermMap = new Map(solarTermArticles.map((term) => [term.name, term]));
const solarTermOrderMap = new Map(solarTermArticles.map((term, index) => [term.name, index]));

export function getSolarTermArticle(name: string): SolarTermArticle {
  const article = solarTermMap.get(name);
  if (!article) {
    throw new Error(`Missing solar term article for ${name}`);
  }
  return article;
}

export function getSolarTermOrder(name: string): number {
  return solarTermOrderMap.get(name) ?? Number.MAX_SAFE_INTEGER;
}
