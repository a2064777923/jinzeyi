function buildBody(input: EntryInput): string {
  const parts = [
    input.detail,
    ...(input.paragraphs ?? []),
    `实用读法：${input.practicalUse}`,
    `文化故事：${input.mythologyStory}`,
    `常见误读：${input.commonMisunderstandings.join('；')}`,
    `来源提示：${input.sourceNotes.join('；')}`,
  ];
  return parts.join('\n\n');
}

